import assert from 'node:assert/strict'
import { JSDOM } from 'jsdom'
import { createServer } from 'vite'

const dom = new JSDOM('<!doctype html><html><body><div id="root"></div></body></html>', {
  url: 'http://localhost:5173/', pretendToBeVisual: true,
})
for (const name of ['window', 'document', 'navigator', 'HTMLElement', 'Element', 'SVGElement', 'Node']) {
  Object.defineProperty(globalThis, name, { configurable: true, value: name === 'window' ? dom.window : dom.window[name] })
}
globalThis.getComputedStyle = dom.window.getComputedStyle.bind(dom.window)
globalThis.requestAnimationFrame = dom.window.requestAnimationFrame.bind(dom.window)
globalThis.cancelAnimationFrame = dom.window.cancelAnimationFrame.bind(dom.window)
globalThis.IS_REACT_ACT_ENVIRONMENT = true
dom.window.scrollTo = () => {}
dom.window.matchMedia = () => ({ matches: false, addListener() {}, removeListener() {}, addEventListener() {}, removeEventListener() {} })

const { createElement: h, StrictMode, useRef, act } = await import('react')
const { createRoot } = await import('react-dom/client')
const vite = await createServer({ server: { middlewareMode: true }, appType: 'custom' })
const errors = []
const root = createRoot(document.getElementById('root'), { onUncaughtError: (error) => errors.push(error) })
let gsap, ScrollTrigger
try {
  const { default: HeroScrollSequence } = await vite.ssrLoadModule('/src/components/hero/HeroScrollSequence.jsx')
  ;({ default: gsap } = await import('gsap'))
  ;({ ScrollTrigger } = await import('gsap/ScrollTrigger'))
  function Fixture({ reducedMotion = false }) {
    const element = useRef(null)
    const cinematic = useRef({ formation: 0, activation: 0, eyes: 0, pulse: -5, progress: 0, entranceDone: false })
    return h('section', { ref: element },
      h('div', { className: 'hero-stage' }, h('div', { className: 'hero-scroll-content' }, 'Hero content')),
      h(HeroScrollSequence, { root: element, cinematic, reducedMotion, skipIntro: true, mobile: false }),
    )
  }
  await act(async () => { root.render(h(StrictMode, null, h(Fixture))) })
  assert.equal(errors.length, 0, errors.map((error) => error.stack).join('\n'))
  assert.match(document.body.textContent, /Hero content/)
  assert.equal(ScrollTrigger.getAll().length, 1, 'Strict Mode must leave exactly one active sequence')
  await act(async () => { root.render(h(StrictMode, null, h(Fixture, { reducedMotion: true }))) })
  assert.equal(ScrollTrigger.getAll().length, 0, 'Reduced motion must remove the scroll sequence')
  await act(async () => { root.render(h(StrictMode, null, h(Fixture))) })
  assert.equal(ScrollTrigger.getAll().length, 1, 'Restoring motion must create only one sequence')
  const { default: About } = await vite.ssrLoadModule('/src/components/sections/About.jsx')
  const { MotionContext } = await vite.ssrLoadModule('/src/context/MotionContext.js')
  const aboutTree = (reducedMotion) => h(StrictMode, null, h(MotionContext.Provider, { value: { reducedMotion } }, h(About)))
  await act(async () => root.render(aboutTree(false)))
  assert.equal(errors.length, 0, errors.map((error) => error.stack).join('\n'))
  const aboutTriggers = ScrollTrigger.getAll().length
  assert.ok(aboutTriggers > 0, 'About must initialize its scoped scroll sequences')
  const nodes = document.querySelectorAll('[aria-controls="about-network-detail"]')
  assert.equal(nodes.length, 6)
  await act(async () => nodes[4].click())
  assert.equal(nodes[4].getAttribute('aria-pressed'), 'true')
  assert.match(document.getElementById('about-network-detail').textContent, /natural language processing/)
  await act(async () => root.render(aboutTree(true)))
  assert.equal(ScrollTrigger.getAll().length, 0, 'About must remove all motion on preference changes')
  for (const heading of document.querySelectorAll('[data-about-heading]')) {
    assert.equal(heading.style.transform, '', 'Reduced motion must restore visible headings')
  }
  await act(async () => root.render(aboutTree(false)))
  assert.equal(ScrollTrigger.getAll().length, aboutTriggers, 'About must not duplicate sequences after motion changes')
  const { default: Skills } = await vite.ssrLoadModule('/src/components/sections/Skills.jsx')
  const skillsTree = (reducedMotion, key = 'desktop') => h(StrictMode, null, h(MotionContext.Provider, { value: { reducedMotion } }, h(Skills, { key })))
  await act(async () => root.render(skillsTree(false)))
  assert.equal(errors.length, 0, errors.map((error) => error.stack).join('\n'))
  assert.equal(ScrollTrigger.getAll().length, 2, 'Skills must leave only its two independent entrances after Strict Mode replay')
  const categories = document.querySelectorAll('.skills-category-control')
  assert.equal(categories.length, 4)
  assert.equal(document.querySelectorAll('.skills-tools li').length, 14)
  await act(async () => categories[1].focus())
  assert.match(document.querySelector('.skills-context').textContent, /Machine Learning & Visualization/)
  assert.equal(categories[1].getAttribute('aria-pressed'), 'false', 'Focus previews without selecting')
  await act(async () => { categories[1].click(); categories[1].blur() })
  assert.equal(categories[1].getAttribute('aria-pressed'), 'true')
  assert.match(document.querySelector('.skills-context').textContent, /Machine Learning & Visualization/)
  await act(async () => categories[2].click())
  assert.equal(categories[1].getAttribute('aria-pressed'), 'false')
  assert.equal(categories[2].getAttribute('aria-pressed'), 'true')
  await act(async () => categories[2].dispatchEvent(new dom.window.KeyboardEvent('keydown', { key: 'Escape', bubbles: true })))
  assert.equal(document.querySelectorAll('.skills-category-control[aria-pressed=true]').length, 0)
  await act(async () => root.render(skillsTree(true)))
  assert.equal(ScrollTrigger.getAll().length, 0, 'Reduced motion must remove Skills entrances')
  assert.equal(document.querySelector('[data-skills-heading]').style.transform, '')
  dom.window.matchMedia = (query) => ({ matches: query === '(max-width: 767px)', addListener() {}, removeListener() {}, addEventListener() {}, removeEventListener() {} })
  await act(async () => root.render(skillsTree(true, 'mobile')))
  const expand = document.querySelector('.skills-expand')
  assert.equal(expand.getAttribute('aria-expanded'), 'true', 'Mobile tools start accessible and expanded')
  await act(async () => expand.click())
  assert.equal(expand.getAttribute('aria-expanded'), 'false')
  assert.equal(document.querySelector('.skills-tools-reveal').getAttribute('aria-hidden'), 'true')
  await act(async () => document.querySelector('.skills-toolbar button').click())
  assert.equal(expand.getAttribute('aria-expanded'), 'true', 'Reset restores the complete mobile ecosystem')
  const { default: Projects } = await vite.ssrLoadModule('/src/components/sections/Projects.jsx')
  const projectTree = (reducedMotion) => h(StrictMode, null, h(MotionContext.Provider, { value: { reducedMotion } }, h(Projects)))
  await act(async () => root.render(projectTree(false)))
  assert.equal(errors.length, 0, errors.map((error) => error.stack).join('\n'))
  assert.equal(ScrollTrigger.getAll().length, 1, 'Projects entrance must not duplicate in Strict Mode')
  const choices = document.querySelectorAll('.projects-index button')
  assert.equal(choices.length, 6)
  for (let i = 0; i < 6; i++) {
    await act(async () => choices[i].click())
    assert.equal(choices[i].getAttribute('aria-current'), 'true')
    assert.ok(document.querySelector('.project-github').href.includes('github.com/khaled-amireh/'))
    assert.equal(document.querySelectorAll('.project-slide').length, 1)
    assert.equal(document.querySelectorAll('.projects-index [aria-current=true]').length, 1)
  }
  await act(async () => document.querySelector('[aria-label="Next project"]').click())
  assert.match(document.querySelector('.project-github').href, /Credit-Card-Fraud-Detection$/)
  await act(async () => document.querySelector('[aria-label="Previous project"]').dispatchEvent(new dom.window.KeyboardEvent('keydown', { key: 'ArrowLeft', bubbles: true })))
  assert.match(document.querySelector('.project-github').href, /House-Price-Prediction-MLR$/)
  await act(async () => { choices[1].click(); choices[3].click(); choices[2].click() })
  assert.match(document.querySelector('.project-github').href, /Customer-Churn-Prediction$/)
  await act(async () => root.render(projectTree(true)))
  assert.equal(ScrollTrigger.getAll().length, 0, 'Projects motion must clean up on preference change')
  assert.equal(document.querySelector('.project-art').style.clipPath, '')
  assert.equal(document.querySelector('[data-project-title]').style.transform, '')
  const { default: Experience } = await vite.ssrLoadModule('/src/components/sections/Experience.jsx')
  const journeyTree = (reducedMotion) => h(StrictMode, null, h(MotionContext.Provider, { value: { reducedMotion } }, h(Experience)))
  await act(async () => root.render(journeyTree(false)))
  assert.equal(errors.length, 0, errors.map((error) => error.stack).join('\n'))
  assert.equal(document.querySelectorAll('[data-journey-entry]').length, 2)
  assert.ok(ScrollTrigger.getAll().length > 0, 'Journey must register scroll reveals')
  await act(async () => root.render(journeyTree(true)))
  assert.equal(ScrollTrigger.getAll().length, 0, 'Reduced motion must remove Journey ScrollTriggers')
  assert.equal(document.querySelector('[data-journey-heading]').style.transform, '')
  await act(async () => root.render(journeyTree(false)))
  assert.ok(ScrollTrigger.getAll().length > 0, 'Restoring motion must restore Journey scroll reveals')
  const { default: Certifications } = await vite.ssrLoadModule('/src/components/sections/Certifications.jsx')
  const credentialsTree = (reducedMotion) => h(StrictMode, null, h(MotionContext.Provider, { value: { reducedMotion } }, h(Certifications)))
  await act(async () => root.render(credentialsTree(false)))
  assert.equal(errors.length, 0, errors.map((error) => error.stack).join('\n'))
  assert.equal(document.querySelectorAll('[data-credential]').length, 2)
  assert.equal(document.querySelectorAll('.credential-action[target="_blank"][rel="noopener noreferrer"]').length, 2)
  assert.equal(document.querySelectorAll('.credential-image-wrap img').length, 2)
  assert.equal(ScrollTrigger.getAll().length, 3, 'Strict Mode must leave one heading and two certificate reveals')
  await act(async () => root.render(credentialsTree(true)))
  assert.equal(ScrollTrigger.getAll().length, 0, 'Reduced motion must remove certificate reveals')
  assert.equal(document.querySelector('[data-credentials-heading]').style.transform, '')
  await act(async () => root.render(credentialsTree(false)))
  assert.equal(ScrollTrigger.getAll().length, 3, 'Restoring motion must not duplicate certificate reveals')
  const { default: Contact } = await vite.ssrLoadModule('/src/components/sections/Contact.jsx')
  const contactTree = (reducedMotion) => h(StrictMode, null, h(MotionContext.Provider, { value: { reducedMotion } }, h(Contact)))
  await act(async () => root.render(contactTree(false)))
  assert.equal(errors.length, 0, errors.map((error) => error.stack).join('\n'))
  assert.equal(document.querySelectorAll('.contact-actions a').length, 2)
  assert.equal(document.querySelectorAll('.contact-socials a').length, 2)
  assert.match(document.body.textContent, /SOMETHING INTELLIGENT/)
  await act(async () => root.render(contactTree(true)))
  assert.equal(ScrollTrigger.getAll().length, 0, 'Reduced motion must remove Contact ScrollTriggers')
  assert.equal(document.querySelector('[data-contact-heading]').style.transform, '')
  await act(async () => root.render(contactTree(false)))
  assert.ok(ScrollTrigger.getAll().length <= 2, 'Restoring motion must not duplicate Contact reveals')
  await act(async () => root.unmount())
  assert.equal(ScrollTrigger.getAll().length, 0, 'ScrollTriggers must be removed on unmount')
  console.log('PASS: Full portfolio client mount; gallery navigation, category interaction, reduced-motion changes, Strict Mode replay, and ScrollTrigger cleanup (simulated DOM; not a visual browser test).')
} finally {
  await act(async () => root.unmount())
  ScrollTrigger?.disable()
  gsap?.ticker.sleep()
  await vite.close()
  dom.window.close()
}
